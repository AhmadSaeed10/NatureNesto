// Tailwind v4 reads its theme from CSS, so tokens.ts is compiled to an @theme block here
// to keep a single source of truth.
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { TOKENS } from "../src/lib/tokens.ts";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outFile = resolve(root, "src/styles/tokens.css");

const kebab = (s: string): string => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

const lines: string[] = [];
const push = (name: string, value: string): void => {
  lines.push(`  --${name}: ${value};`);
};

// Clearing the default palette means only brand colours exist as utilities.
lines.push("  --color-*: initial;");
for (const [name, value] of Object.entries(TOKENS.color)) push(`color-${kebab(name)}`, value);

for (const [name, value] of Object.entries(TOKENS.radius)) push(`radius-${kebab(name)}`, value);

for (const [name, t] of Object.entries(TOKENS.text)) {
  push(`text-${name}`, t.size);
  push(`text-${name}--line-height`, t.leading);
  push(`text-${name}--letter-spacing`, t.tracking);
}

push("ease-brand", TOKENS.motion.ease);
push("duration-micro", TOKENS.motion.durationMicro);
push("duration-reveal", TOKENS.motion.durationReveal);
push("size-tap", TOKENS.size.tapTarget);
push("grain-opacity", TOKENS.texture.grainOpacity);

const css = `/* Generated by scripts/build-tokens.ts from src/lib/tokens.ts. Do not edit by hand. */
@theme {
${lines.join("\n")}
}
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, css);
console.log(`tokens: wrote ${lines.length} properties to src/styles/tokens.css`);
